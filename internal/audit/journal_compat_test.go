func TestAJournalWrittenBeforeVerifiedApproversStillVerifies(t *testing.T) {
	path := filepath.Join(t.TempDir(), "audit.jsonl")
	contents := strings.TrimLeft(preChangeJournal, "\n")
	if err := os.WriteFile(path, []byte(contents), 0o600); err != nil {
		t.Fatal(err)
	}

	// The fixture must be what it claims to be. A "pre-change" journal that somehow carried the
	// field would make the assertion below hold for the wrong reason, forever.
	if strings.Contains(contents, "verified_approvers") {
		t.Fatal("the pre-change fixture carries verified_approvers, so it is not pre-change and this test proves nothing")
	}

	events, err := Verify(path)
	if err != nil {
		t.Fatalf("a journal written before verified_approvers existed no longer verifies: %v\n"+
			"Every journal an operator holds is now unverifiable. If a field was added, it needs omitempty.", err)
	}
	if len(events) != 3 {
		t.Fatalf("verified %d events, want 3", len(events))
	}
}
