// A JOURNAL WRITTEN BEFORE verified_approvers EXISTED MUST STILL VERIFY.
//
// Event hashes cover json.Marshal of the whole struct, so ANY change to the marshalled byte
// stream makes every previously written event fail Verify. RBACDigest did exactly that, and
// TestVerifyRefusesPreRBACDigestEvents pins it as a deliberate upgrade-day cost.
//
// TestAnEventWithoutApproversMarshalsWithoutTheField asserts that verified_approvers is omitted
// when empty. That is NECESSARY BUT NOT SUFFICIENT for "existing journals keep verifying", and
// the difference is not pedantic. Add the next field without omitempty --
//
//	VerifiedApprovers []string `json:"verified_approvers,omitempty"`
//	SiteID            string   `json:"site_id"`
//
// -- and that test still passes while every journal in existence becomes unverifiable. Measured,
// not supposed. It is also the exact mistake RBACDigest already made once.
//
// THE FIXTURE IS A PASTED LITERAL ON PURPOSE. A journal generated by the current code cannot
// detect a change in the current code: it would move along with the struct and agree with itself
// forever. That is the same self-referential trap as a verifier whose search space includes the
// artifact it is checking. These bytes were emitted by the audit package at the commit before
// verified_approvers existed; the device identifier was neutralised for public release and the
// chain recomputed once at that time. Do not regenerate them again.
